'''
[역할]
너는 파이썬 데이터 처리를 돕는 조교다. 대학교 1학년이 읽을 코드를 쓴다.

[목표]
아래 명세대로 CSV를 정제하는 함수 정제(df) 를 만들어라.

[데이터]
  파일: scores_2026.csv, 114행 5열
  열: 학번(문자), 이름(문자), 반(문자), 과목(문자), 점수(정수)
  점수는 0 이상 100 이하의 정수여야 한다.
  반과 과목 값의 앞뒤에 공백이 섞여 있다.
  점수가 비어 있는 행이 있다. (빈 칸은 결시이지 0점이 아니다)
  모든 열이 완전히 같은 행이 중복으로 들어 있다.

[처리 규칙]
  1) 점수가 비어 있는 행은 삭제한다.
  2) 모든 열이 완전히 같은 행은 하나만 남긴다.
  3) 반과 과목의 앞뒤 공백을 제거한다.
  4) 점수가 0~100 밖인 행은 삭제한다.

[제약]
  - pandas 만 사용한다. 다른 라이브러리를 쓰지 마라.
  - 각 단계가 끝날 때마다 남은 행 수를 print 하라.
  - 원본 df 를 직접 고치지 말고 복사본을 만들어 작업하라.
  - 한 줄짜리 주석으로 각 단계가 무엇을 하는지 적어라.

# ① 필터링
정제된 df에서 과목이 '수학'인 행만 남기는 코드를 한 줄로 써라.
그리고 남은 행 수를 print 하라.


# ② 그룹화
정제된 df를 '반'으로 묶어 점수 평균을 내는 코드를 써라.
그다음 '과목'과 '반' 두 기준으로 묶는 코드도 따로 써라.


# ③ 통계
'반'으로 묶어 개수 · 평균 · 중앙값 · 최댓값을 한 표로 내는
코드를 써라. 소수 둘째 자리까지 반올림하라.
'''

import pandas as pd

def 정제(df):
    df = df.copy()
    print(f"시작: {len(df)}행")

    # 1) 점수가 비어 있는 행은 삭제한다.
    df = df.dropna(subset=["점수"])
    print(f"1) 점수가 비어 있는 행 삭제 후: {len(df)}행")

    # 2) 모든 열이 완전히 같은 행은 하나만 남긴다.
    df = df.drop_duplicates()
    print(f"2) 중복 행 제거 후: {len(df)}행")

    # 3) 반과 과목의 앞뒤 공백을 제거한다.
    #df["반"] = df["반"].str.strip()
    #df["과목"] = df["과목"].str.strip()
    print(f"3) 공백 제거 후: {len(df)}행")

    # 4) 점수가 0~100 밖인 행은 삭제한다.
    df = df[(df["점수"] >= 0) & (df["점수"] <= 100)]
    print(f"4) 점수 범위 확인 후: {len(df)}행")

    return df

def 수학만(df):
    # 과목이 '수학'인 행만 남긴다
    return df[df["과목"] == "수학"]


def 일반반_90이상(df):
    # 1반이면서 90점 이상인 행만 남긴다
    return df[(df["반"] == "1반") & (df["점수"] >= 90)]

def 반별_평균표(df):
    # 반으로 묶어 점수 평균
    return df.groupby("반")["점수"].mean()


def 과목반별_평균표(df):
    # 과목과 반 두 기준으로 묶어 점수 평균
    return df.groupby(["과목", "반"])["점수"].mean()

def 반별통계(df):
    # 반별 개수·평균·중앙값·최댓값을 한 표로 (소수 둘째 자리까지)
    return df.groupby("반")["점수"].agg(["count", "mean", "median", "max"]).round(2)


def 반별평균(df):
    # 반 이름 → 평균 점수 (Series). 예: 반별평균(df)["1반"]
    return df.groupby("반")["점수"].mean().round(2)


if __name__ == "__main__":
    df = 정제(pd.read_csv("scores_2026.csv"))

    수학 = 수학만(df)
    print(f"\n[필터링] 수학 행 수: {len(수학)}")
    print(f"[필터링] 1반이면서 90점 이상 행 수: {len(일반반_90이상(df))}")

    print("\n[그룹화] 반별 평균")
    print(반별_평균표(df))
    print("\n[그룹화] 과목 × 반 평균")
    print(과목반별_평균표(df))

    print("\n[통계] 반별 개수·평균·중앙값·최댓값")
    print(반별통계(df))

    print("\n[검증] 합계 일치")
    print("그룹 합의 합:", df.groupby("반")["점수"].sum().sum(), "/ 전체 합:", df["점수"].sum())
    print("그룹 개수의 합:", df.groupby("반")["점수"].count().sum(), "/ 전체 행 수:", len(df))

    print("\n[검증] 스팟 체크: 1반 × 수학")
    칸 = df[(df["반"] == "1반") & (df["과목"] == "수학")]["점수"]
    print("값:", list(칸), "/ 합:", 칸.sum(), "/ 개수:", len(칸), "/ 평균:", 칸.sum() / len(칸))







